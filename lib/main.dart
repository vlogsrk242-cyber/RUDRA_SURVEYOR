class UnitPage extends StatefulWidget {
  const UnitPage({super.key});

  @override
  State<UnitPage> createState() =>
      _UnitPageState();
}

class _UnitPageState
    extends State<UnitPage> {

  final input =
      TextEditingController();

  String from = 'Meter';
  String to = 'Feet';
  String result = '0';

  final units = [
    'Meter',
    'Feet',
    'Inch',
    'Yard',
  ];

  double meterValue(
    double value,
    String unit,
  ) {
    if (unit == 'Feet') {
      return value * 0.3048;
    }

    if (unit == 'Inch') {
      return value * 0.0254;
    }

    if (unit == 'Yard') {
      return value * 0.9144;
    }

    return value;
  }

  double convertFromMeter(
    double value,
    String unit,
  ) {
    if (unit == 'Feet') {
      return value / 0.3048;
    }

    if (unit == 'Inch') {
      return value / 0.0254;
    }

    if (unit == 'Yard') {
      return value / 0.9144;
    }

    return value;
  }

  void convert() {
    final value =
        double.tryParse(input.text) ?? 0;

    final meters =
        meterValue(value, from);

    final converted =
        convertFromMeter(
      meters,
      to,
    );

    setState(() {
      result =
          converted.toStringAsFixed(4);
    });
  }

  @override
  void dispose() {
    input.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title:
            const Text('Unit Conversion'),
        backgroundColor:
            const Color(0xFF7B1FA2),
        foregroundColor: Colors.white,
      ),
      body: ListView(
        padding:
            const EdgeInsets.all(16),
        children: [

          AppField(
            controller: input,
            label: 'Value',
            icon: Icons.numbers,
            keyboard:
                const TextInputType
                    .numberWithOptions(
              decimal: true,
            ),
          ),

          DropdownButtonFormField<String>(
            initialValue: from,
            decoration:
                const InputDecoration(
              labelText: 'From',
              border:
                  OutlineInputBorder(),
            ),
            items: units
                .map(
                  (u) => DropdownMenuItem(
                    value: u,
                    child: Text(u),
                  ),
                )
                .toList(),
            onChanged: (v) {
              if (v != null) {
                setState(() {
                  from = v;
                });
              }
            },
          ),

          const SizedBox(height: 12),

          DropdownButtonFormField<String>(
            initialValue: to,
            decoration:
                const InputDecoration(
              labelText: 'To',
              border:
                  OutlineInputBorder(),
            ),
            items: units
                .map(
                  (u) => DropdownMenuItem(
                    value: u,
                    child: Text(u),
                  ),
                )
                .toList(),
            onChanged: (v) {
              if (v != null) {
                setState(() {
                  to = v;
                });
              }
            },
          ),

          const SizedBox(height: 15),

          ElevatedButton(
            onPressed: convert,
            child:
                const Text('Convert'),
          ),

          const SizedBox(height: 20),

          Center(
            child: Text(
              '$result $to',
              style: const TextStyle(
                fontSize: 28,
                fontWeight:
                    FontWeight.bold,
                color:
                    Color(0xFF7B1FA2),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

