class LandEntryPage extends StatefulWidget {
  const LandEntryPage({super.key});
  @override
  State<LandEntryPage> createState() => _LandEntryPageState();
}

class _LandEntryPageState extends State<LandEntryPage> {
  final owner = TextEditingController();
  final mobile = TextEditingController();
  final village = TextEditingController();
  final taluka = TextEditingController();
  final survey = TextEditingController();
  final payment = TextEditingController();
  DateTime date = DateTime.now();
  File? selectedFile;
  String? selectedFileName;
  bool saving = false;

  @override
  void dispose() {
    owner.dispose(); mobile.dispose(); village.dispose(); taluka.dispose(); survey.dispose(); payment.dispose();
    super.dispose();
  }

  Future<void> chooseDate() async {
    final d = await showDatePicker(context: context, initialDate: date, firstDate: DateTime(2000), lastDate: DateTime(2100));
    if (d != null) setState(() => date = d);
  }

  Future<void> pickFile() async {
    final result = await FilePicker.platform.pickFiles(withData: false, allowMultiple: false);
    if (result == null || result.files.single.path == null) return;
    final picked = File(result.files.single.path!);
    final dir = await getApplicationDocumentsDirectory();
    final saveDir = Directory('${dir.path}/SavedFiles');
    if (!await saveDir.exists()) await saveDir.create(recursive: true);
    final safeName = '${DateTime.now().millisecondsSinceEpoch}_${result.files.single.name.replaceAll(RegExp(r'[\\/:*?"<>|]'), '_')}';
    final saved = await picked.copy('${saveDir.path}/$safeName');
    setState(() {
      selectedFile = saved;
      selectedFileName = result.files.single.name;
    });
  }

  Future<void> save() async {
    if (owner.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('માલિકનું નામ દાખલ કરો')));
      return;
    }
    setState(() => saving = true);
    try {
      String? savedPath;
      if (selectedFile != null) {
        savedPath = selectedFile!.path;
        await HistoryStore.addFile({'name': selectedFileName ?? selectedFile!.uri.pathSegments.last, 'path': savedPath, 'date': DateTime.now().toIso8601String()});
      }
      final record = {
        'owner': owner.text.trim(),
        'mobile': mobile.text.trim(),
        'village': village.text.trim(),
        'taluka': taluka.text.trim(),
        'survey': survey.text.trim(),
        'date': '${date.day}/${date.month}/${date.year}',
        'payment': payment.text.trim(),
        'fileName': selectedFileName ?? '',
        'filePath': savedPath ?? '',
      };
      await HistoryStore.addRecord(record);
      final pdf = await PdfService.createReport(record);
      if (!mounted) return;
      await showDialog<void>(
        context: context,
        builder: (_) => AlertDialog(
          title: const Text('Saved Successfully'),
          content: Text(selectedFileName == null ? 'Record saved. PDF report is ready.' : 'Record and file saved. PDF report is ready.'),
          actions: [
            TextButton(onPressed: () { Navigator.pop(context); Printing.layoutPdf(onLayout: (_) async => pdf.readAsBytes()); }, child: const Text('Preview PDF')),
            TextButton(onPressed: () { Navigator.pop(context); Share.shareXFiles([XFile(pdf.path)], text: 'RUDRA SURVEYOR Report'); }, child: const Text('Share')),
            FilledButton(onPressed: () => Navigator.pop(context), child: const Text('Done')),
          ],
        ),
      );
    } catch (e) {
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Save error: $e')));
    } finally {
      if (mounted) setState(() => saving = false);
    }
  }

  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(title: const Text('OP1 • Land Entry')),
        body: ListView(
          padding: const EdgeInsets.all(16),
          children: [
            AppField(controller: owner, label: 'માલિકનું નામ', icon: Icons.person),
            AppField(controller: mobile, label: 'મોબાઇલ નંબર', icon: Icons.phone, keyboard: TextInputType.phone),
            AppField(controller: village, label: 'ગામ', icon: Icons.location_city),
            AppField(controller: taluka, label: 'તાલુકો', icon: Icons.location_on),
            AppField(controller: survey, label: 'સર્વે નંબર', icon: Icons.numbers),
            InkWell(
              onTap: chooseDate,
              child: InputDecorator(decoration: const InputDecoration(labelText: 'માપણીની તારીખ', prefixIcon: Icon(Icons.calendar_month), border: OutlineInputBorder()), child: Text('${date.day}/${date.month}/${date.year}')),
            ),
            const SizedBox(height: 14),
            AppField(controller: payment, label: 'કુલ પેમેન્ટ (₹)', icon: Icons.currency_rupee, keyboard: const TextInputType.numberWithOptions(decimal: true)),
            const SizedBox(height: 14),
            OutlinedButton.icon(onPressed: pickFile, icon: const Icon(Icons.upload_file), label: Text(selectedFileName == null ? 'Upload a File' : 'Selected: $selectedFileName')),
            if (selectedFileName != null) ...[
              const SizedBox(height: 8),
              Text('File will be saved inside the app.', style: TextStyle(color: Colors.grey.shade700)),
            ],
            const SizedBox(height: 20),
            SizedBox(height: 54, child: FilledButton.icon(onPressed: saving ? null : save, icon: saving ? const SizedBox(width: 20, height: 20, child: CircularProgressIndicator(strokeWidth: 2, color: Colors.white)) : const Icon(Icons.save), label: Text(saving ? 'Saving...' : 'Save + PDF Report'))),
          ],
        ),
      );
}

