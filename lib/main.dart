class HistoryStore {
  static const recordsKey = 'land_records';
  static const filesKey = 'saved_files';

  static Future<List<Map<String, dynamic>>> records() async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(recordsKey) ?? [];
    return list.map<Map<String, dynamic>>((e) {
      try {
        return Map<String, dynamic>.from(jsonDecode(e) as Map);
      } catch (_) {
        return <String, dynamic>{};
      }
    }).where((e) => e.isNotEmpty).toList();
  }

  static Future<void> addRecord(Map<String, dynamic> record) async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(recordsKey) ?? [];
    list.add(jsonEncode(record));
    await p.setStringList(recordsKey, list);
  }

  static Future<void> deleteRecord(int index) async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(recordsKey) ?? [];
    if (index >= 0 && index < list.length) {
      list.removeAt(index);
      await p.setStringList(recordsKey, list);
    }
  }

  static Future<void> addFile(Map<String, dynamic> file) async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(filesKey) ?? [];
    list.add(jsonEncode(file));
    await p.setStringList(filesKey, list);
  }

  static Future<List<Map<String, dynamic>>> files() async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(filesKey) ?? [];
    return list.map<Map<String, dynamic>>((e) {
      try {
        return Map<String, dynamic>.from(jsonDecode(e) as Map);
      } catch (_) {
        return <String, dynamic>{};
      }
    }).where((e) => e.isNotEmpty).toList();
  }

  static Future<void> deleteFile(int index) async {
    final p = await SharedPreferences.getInstance();
    final list = p.getStringList(filesKey) ?? [];
    if (index >= 0 && index < list.length) {
      final item = jsonDecode(list[index]);
      final path = item is Map ? item['path']?.toString() : null;
      if (path != null) {
        try {
          final f = File(path);
          if (await f.exists()) await f.delete();
        } catch (_) {}
      }
      list.removeAt(index);
      await p.setStringList(filesKey, list);
    }
  }
}

class PdfService {
  static Future<File> createReport(Map<String, dynamic> r) async {
    final doc = pw.Document();
    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        build: (_) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Center(
              child: pw.Text('RUDRA SURVEYOR', style: pw.TextStyle(fontSize: 25, fontWeight: pw.FontWeight.bold)),
            ),
            pw.SizedBox(height: 5),
            pw.Center(child: pw.Text('LAND SURVEY REPORT', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold))),
            pw.SizedBox(height: 18),
            pw.Divider(),
            _row('Owner Name', r['owner']),
            _row('Mobile Number', r['mobile']),
            _row('Village', r['village']),
            _row('Taluka', r['taluka']),
            _row('Survey Number', r['survey']),
            _row('Survey Date', r['date']),
            _row('Total Payment', 'Rs. ${r['payment'] ?? '0'}'),
            if ((r['fileName'] ?? '').toString().isNotEmpty) _row('Uploaded File', r['fileName']),
            pw.SizedBox(height: 25),
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfColors.grey)),
              child: pw.Text('This report is generated by RUDRA SURVEYOR application.', style: const pw.TextStyle(fontSize: 10)),
            ),
            pw.Spacer(),
            pw.Center(child: pw.Text('RUDRA SURVEYOR', style: pw.TextStyle(fontWeight: pw.FontWeight.bold))),
          ],
        ),
      ),
    );
    final dir = await getApplicationDocumentsDirectory();
    final file = File('${dir.path}/RUDRA_SURVEY_${DateTime.now().millisecondsSinceEpoch}.pdf');
    await file.writeAsBytes(await doc.save());
    return file;
  }

  static pw.Widget _row(String title, dynamic value) => pw.Padding(
        padding: const pw.EdgeInsets.only(bottom: 10),
        child: pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.SizedBox(width: 145, child: pw.Text(title, style: pw.TextStyle(fontWeight: pw.FontWeight.bold))),
            pw.Expanded(child: pw.Text(value?.toString() ?? '-')),
          ],
        ),
      );

  static Future<void> preview(Map<String, dynamic> r) async {
    final file = await createReport(r);
    final bytes = await file.readAsBytes();
    await Printing.layoutPdf(onLayout: (_) async => bytes);
  }

  static Future<void> share(Map<String, dynamic> r) async {
    final file = await createReport(r);
    await Share.shareXFiles([XFile(file.path)], text: 'RUDRA SURVEYOR Report');
  }
}

