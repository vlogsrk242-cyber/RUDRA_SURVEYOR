    return Padding(
      padding:
          const EdgeInsets.only(
        bottom: 14,
      ),
      child: TextFormField(
        controller: controller,
        keyboardType: keyboard,
        onChanged: onChanged,
        validator: (value) {
          if (value == null ||
              value.trim().isEmpty) {
            return '$label લખો';
          }
          return null;
        },
        decoration:
            InputDecoration(
          labelText: label,
          prefixIcon:
              Icon(icon),
          border:
              OutlineInputBorder(
            borderRadius:
                BorderRadius.circular(
              14,
            ),
          ),
          filled: true,
          fillColor:
              Colors.white,
