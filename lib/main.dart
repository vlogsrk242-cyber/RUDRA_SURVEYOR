                'Length',
                '${record['length'] ?? '0'} Meter',
              ),

              _pdfRow(
                'Width',
                '${record['width'] ?? '0'} Meter',
              ),

              _pdfRow(
                'Total Area',
                '${record['area'] ?? '0'} Square Meter',
              ),

              _pdfRow(
                'Total Payment',
                'Rs. ${record['payment'] ?? '0'}',
              ),

              pw.SizedBox(height: 30),

              pw.Container(
                padding: const pw.EdgeInsets.all(12),
                decoration: pw.BoxDecoration(
                  border: pw.Border.all(
                    color: PdfColors.grey,
