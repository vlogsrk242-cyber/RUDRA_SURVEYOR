class UnitPage extends StatefulWidget {
  const UnitPage({super.key});
  @override
  State<UnitPage> createState() => _UnitPageState();
}

class _UnitPageState extends State<UnitPage> {
  final input = TextEditingController();
  String from = 'Meter';
  String to = 'Feet';
  String result = '0';

  final units = const ['Meter', 'Feet', 'Inch', 'Yard', 'm²', 'ft²', 'yd²', 'Acre', 'Hectare', 'Guntha'];
  final areaUnits = const {'m²', 'ft²', 'yd²', 'Acre', 'Hectare', 'Guntha'};

  double toBase(double v, String unit) {
    switch (unit) {
      case 'Feet': return v * 0.3048;
      case 'Inch': return v * 0.0254;
      case 'Yard': return v * 0.9144;
      case 'ft²': return v * 0.09290304;
      case 'yd²': return v * 0.83612736;
      case 'Acre': return v * 4046.8564224;
      case 'Hectare': return v * 10000;
      case 'Guntha': return v * 101.17141056;
      default: return v;
    }
  }

  double fromBase(double v, String unit) {
    switch (unit) {
      case 'Feet': return v / 0.3048;
      case 'Inch': return v / 0.0254;
      case 'Yard': return v / 0.9144;
      case 'ft²': return v / 0.09290304;
      case 'yd²': return v / 0.83612736;
      case 'Acre': return v / 4046.8564224;
      case 'Hectare': return v / 10000;
      case 'Guntha': return v / 101.17141056;
      default: return v;
    }
  }

  void convert() {
    final v = double.tryParse(input.text) ?? 0;
    final bothArea = areaUnits.contains(from) && areaUnits.contains(to);
    final bothLength = !areaUnits.contains(from) && !areaUnits.contains(to);
    if (!bothArea && !bothLength) {
      setState(() => result = 'Length અને Area units mix કરી શકાતા નથી');
      return;
    }
    setState(() => result = fromBase(toBase(v, from), to).toStringAsFixed(4));
  }

  @override
  void dispose() { input.dispose(); super.dispose(); }

  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(title: const Text('OP3 • Unit Conversion')),
        body: ListView(padding: const EdgeInsets.all(16), children: [
          AppField(controller: input, label: 'Value', icon: Icons.numbers, keyboard: const TextInputType.numberWithOptions(decimal: true)),
          DropdownButtonFormField<String>(value: from, decoration: const InputDecoration(labelText: 'From', border: OutlineInputBorder()), items: units.map((u) => DropdownMenuItem(value: u, child: Text(u))).toList(), onChanged: (v) { if (v != null) setState(() => from = v); }),
          const SizedBox(height: 12),
          DropdownButtonFormField<String>(value: to, decoration: const InputDecoration(labelText: 'To', border: OutlineInputBorder()), items: units.map((u) => DropdownMenuItem(value: u, child: Text(u))).toList(), onChanged: (v) { if (v != null) setState(() => to = v); }),
          const SizedBox(height: 15),
          FilledButton(onPressed: convert, child: const Text('Convert')),
          const SizedBox(height: 20),
