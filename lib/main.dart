class LandEntryPage extends StatefulWidget {
  const LandEntryPage({super.key});

  @override
  State<LandEntryPage> createState() =>
      _LandEntryPageState();
}

class _LandEntryPageState
    extends State<LandEntryPage> {

  final formKey =
      GlobalKey<FormState>();

  final owner =
      TextEditingController();

  final mobile =
      TextEditingController();

  final village =
      TextEditingController();

  final taluka =
      TextEditingController();

  final survey =
      TextEditingController();

  final length =
      TextEditingController();

  final width =
      TextEditingController();

  final payment =
      TextEditingController();

  DateTime date = DateTime.now();

  double area = 0;

  @override
  void dispose() {
    owner.dispose();
    mobile.dispose();
    village.dispose();
    taluka.dispose();
    survey.dispose();
    length.dispose();
    width.dispose();
    payment.dispose();
    super.dispose();
  }

  void calculateArea() {
    final l =
        double.tryParse(length.text) ?? 0;

    final w =
        double.tryParse(width.text) ?? 0;

    setState(() {
      area = l * w;
    });
  }

  Future<void> chooseDate() async {
    final result =
        await showDatePicker(
      context: context,
      initialDate: date,
      firstDate:
          DateTime(2000),
      lastDate:
          DateTime(2100),
    );

    if (result != null) {
      setState(() {
        date = result;
      });
    }
  }

  Future<void> save() async {
    if (!formKey.currentState!
        .validate()) {
      return;
    }

    calculateArea();

    final record = {
      'owner': owner.text.trim(),
      'mobile': mobile.text.trim(),
      'village': village.text.trim(),
      'taluka': taluka.text.trim(),
      'survey': survey.text.trim(),
      'length': length.text.trim(),
      'width': width.text.trim(),
      'area': area.toStringAsFixed(2),
      'payment': payment.text.trim(),
      'date':
          '${date.day}/${date.month}/${date.year}',
    };

    await HistoryStore.addRecord(
      record,
    );

    if (!mounted) return;

    await showDialog(
      context: context,
      builder: (_) {
        return AlertDialog(
          title: const Text(
            'Save Successful ✅',
          ),
          content: const Text(
            'જમીન માપણીની નોંધ Save થઈ ગઈ છે.\n\nહવે PDF બનાવીને WhatsApp દ્વારા મોકલી શકો છો.',
          ),
          actions: [
            TextButton(
              onPressed: () =>
                  Navigator.pop(context),
              child: const Text('OK'),
            ),
          ],
        );
      },
    );

    if (!mounted) return;

    await showReportOptions(
      record,
    );
  }

  Future<void> showReportOptions(
    Map<String, dynamic> record,
  ) async {
    await showModalBottomSheet(
      context: context,
      builder: (context) {
        return SafeArea(
          child: Padding(
            padding:
                const EdgeInsets.all(20),
            child: Column(
              mainAxisSize:
                  MainAxisSize.min,
              children: [

                const Text(
                  'Land Survey Report',
                  style: TextStyle(
                    fontSize: 20,
                    fontWeight:
                        FontWeight.bold,
                  ),
                ),

                const SizedBox(height: 20),

                ListTile(
                  leading: const Icon(
                    Icons.picture_as_pdf,
                    color: Colors.red,
                  ),
                  title:
                      const Text('PDF બનાવો / Preview'),
                  onTap: () async {
                    Navigator.pop(context);
                    await PdfService
                        .previewPdf(record);
                  },
                ),

                ListTile(
                  leading: const Icon(
                    Icons.share,
                    color: Colors.green,
                  ),
                  title: const Text(
                    'PDF WhatsApp / Share',
                  ),
                  onTap: () async {
                    Navigator.pop(context);
                    await PdfService
                        .sharePdf(record);
